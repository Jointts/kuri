"""Bakes the Kurimanju PNG frames into raw RGBA atlases the mod reads with $.fs.read (the mod has no zlib).

After baking, run scripts/build-host.sh: host/atlas.ts is part of the helper, and host/dist is what runs.

usage: python3 bake-assets.py <pi-kurimanju>/src/assets/kuri <mod folder> [px=8]
Sprites are authored at 20 image px per world px; they are scaled here to `px` image pixels per world pixel (default 8; keep PX in hooks/kuri/kuri-scene.ts equal to it).
"""
import glob, json, os, sys
from PIL import Image

src, mod = sys.argv[1], sys.argv[2]
px = int(sys.argv[3]) if len(sys.argv) > 3 else 8
LIMIT = 3 * 1024 * 1024  # $.fs.read takes 4 MiB at most; each atlas file stays under it
entries = []
for path in sorted(glob.glob(os.path.join(src, "*.png"))):
    entries.append((os.path.basename(path)[:-4], path))

index, files, blob = {}, [], bytearray()
def flush():
    global blob
    if blob:
        name = "atlas-%d.bin" % len(files)
        with open(os.path.join(mod, "assets", name), "wb") as f:
            f.write(blob)
        files.append(name)
        print(name, len(blob))
        blob = bytearray()

for name, path in entries:
    img = Image.open(path).convert("RGBA").convert("RGBa")
    img = img.resize((round(img.width * px / 20), round(img.height * px / 20)), Image.LANCZOS).convert("RGBA")
    data = img.tobytes()
    if len(blob) + len(data) > LIMIT:
        flush()
    index[name] = ["atlas-%d.bin" % len(files), len(blob), img.width, img.height]
    blob += data
flush()

with open(os.path.join(mod, "host", "atlas.ts"), "w") as f:
    f.write("// Generated by scripts/bake-assets.py: name -> [file, byte offset, width, height] of raw RGBA in assets/.\n")
    f.write("export const ATLAS_FILES: readonly string[] = " + json.dumps(files) + "\n")
    f.write("export const ATLAS: Record<string, readonly [string, number, number, number]> = " + json.dumps(index, indent=1) + "\n")
